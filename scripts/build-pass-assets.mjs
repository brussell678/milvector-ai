// Builds lib/cards/pass-assets.ts: the icon and logo images an Apple Wallet
// pass must carry, resized from the MilVector logo and stored as base64 so
// they ship inside the server bundle.
//
// Run: node scripts/build-pass-assets.mjs

import { writeFileSync } from "node:fs";
import sharp from "sharp";

const SOURCE = "public/assets/milvector-ai-logo-transparent.png";

const sizes = {
  "icon.png": 29,
  "icon@2x.png": 58,
  "icon@3x.png": 87,
  "logo.png": 50,
  "logo@2x.png": 100,
};

const entries = [];
for (const [name, size] of Object.entries(sizes)) {
  const buffer = await sharp(SOURCE)
    .resize(size, size, { fit: "contain", background: { r: 0, g: 0, b: 0, alpha: 0 } })
    .png({ compressionLevel: 9, palette: true })
    .toBuffer();
  entries.push(`  "${name}": "${buffer.toString("base64")}",`);
  console.log(name, buffer.length, "bytes");
}

writeFileSync(
  "lib/cards/pass-assets.ts",
  `// Generated by scripts/build-pass-assets.mjs. Do not edit by hand.\n\nexport const PASS_ASSETS: Record<string, string> = {\n${entries.join("\n")}\n};\n`,
);
